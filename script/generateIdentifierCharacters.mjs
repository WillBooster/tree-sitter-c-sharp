import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

import { directiveIdentifierRanges } from './directiveIdentifierRanges.mjs';

assert.equal(process.argv.length, 4, 'Usage: generateIdentifierCharacters.mjs <parser.c> <header>');
const source = readFileSync(process.argv[2], 'utf8');
const unnamedSymbols = new Set(
  [...source.matchAll(/\[(\w+)\] = \{\s+\.visible = (?:true|false),\s+\.named = false,/g)].map((match) => match[1])
);
const syntaxWords = [
  ...new Set(
    [...source.matchAll(/\[(\w+)\] = "([A-Za-z_]+)",/g)]
      .filter((match) => unnamedSymbols.has(match[1]))
      .map((match) => match[2])
  ),
]
  .filter((word) => word !== 'var')
  .toSorted((left, right) => (left < right ? -1 : left > right ? 1 : 0));
assert.ok(syntaxWords.length > 0, 'Missing generated syntax words');
const names = new Set(
  [...source.matchAll(/\b(ts_lex_sym__identifier_token_character_set_\d+)_ascii, /g)].map((match) => match[1])
);
const candidates = [...names].map(readTable);
const letters = 'AZaz_'.split('').map((character) => character.codePointAt(0));
const digits = '0123456789'.split('').map((character) => character.codePointAt(0));
const starts = candidates.filter(
  (table) =>
    letters.every((character) => containsAscii(table, character)) &&
    digits.every((character) => !containsAscii(table, character))
);
const continues = candidates.filter((table) =>
  [...letters, ...digits].every((character) => containsAscii(table, character))
);
assert.equal(starts.length, 1, 'Expected one identifier-start set with letters/underscore but no digits');
assert.equal(continues.length, 1, 'Expected one identifier-continuation set with letters/underscore and digits');
const tables = [starts[0], continues[0]];
assert.ok(tables[0] && tables[1]);
for (let character = 0; character < 128; character++) {
  const isStart =
    (character >= 0x41 && character <= 0x5a) || (character >= 0x61 && character <= 0x7a) || character === 0x5f;
  const isContinue = isStart || (character >= 0x30 && character <= 0x39);
  assert.equal(
    character !== 0x5c && containsAscii(tables[0], character),
    isStart,
    `Unexpected ASCII identifier-start membership for U+${character.toString(16)}`
  );
  assert.equal(
    character !== 0x5c && containsAscii(tables[1], character),
    isContinue,
    `Unexpected ASCII identifier-continuation membership for U+${character.toString(16)}`
  );
}

function readTable(name) {
  const declarations = [
    ...source.matchAll(new RegExp(`static const [^;]+\\b${name}(?:_\\w+)?\\[[\\s\\S]*?\\n?};`, 'g')),
  ];
  assert.ok(declarations.length > 0, `Missing generated identifier tables: ${name}`);
  const calls = [
    ...source.matchAll(
      new RegExp(`(ts_lex_\\w+_contains(?:_with_ascii)?)\\((${name}_ascii, [^\\n]+?), lookahead\\)`, 'g')
    ),
  ];
  const expressions = new Set(calls.map((match) => `${match[1]}(${match[2]}, character)`));
  assert.equal(expressions.size, 1, `Expected one identifier lookup representation: ${name}`);
  const [expression] = expressions;
  assert.ok(expression, `Missing identifier lookup: ${name}`);
  const ascii = source.match(new RegExp(`static const uint32_t ${name}_ascii\\[\\] = \\{([^}]+)\\}`));
  assert.ok(ascii, `Missing generated ASCII identifier table: ${name}`);
  const words = [...ascii[1].matchAll(/0x[\da-f]+|\b\d+\b/gi)].map((match) => Number(match[0]));
  assert.equal(words.length, 4, `Expected 128 ASCII identifier bits: ${name}`);
  return { declarations: declarations.map((match) => match[0]).join('\n'), expression, words };
}

function containsAscii(table, character) {
  return ((table.words[character >>> 5] >>> (character & 31)) & 1) !== 0;
}
const helpers = [...new Set(tables.map(({ expression }) => expression.slice(0, expression.indexOf('('))))].map(
  (name) => {
    const matches = [...source.matchAll(new RegExp(`static inline bool ${name}\\([\\s\\S]*?\\n}`, 'g'))];
    assert.equal(matches.length, 1, `Expected one generated lookup helper: ${name}`);
    return matches[0][0];
  }
);
const header = `/* Generated by script/generateIdentifierCharacters.mjs from parser tables and Unicode properties. */
#ifndef TREE_SITTER_C_SHARP_IDENTIFIER_CHARACTERS_H_
#define TREE_SITTER_C_SHARP_IDENTIFIER_CHARACTERS_H_

#include "tree_sitter/parser.h"
#include <string.h>
#include <wctype.h>

static inline bool buf_equals(const char *buf, size_t n, const char *kw) {
    for (size_t i = 0; i < n; i++) {
        if (!kw[i] || buf[i] != kw[i]) return false;
    }
    return !kw[n];
}

// web-tree-sitter.wasm omits strchr; non-literal sets cannot lower to memchr.
static inline bool is_ascii_in(int32_t c, const char *characters) {
    if ((uint32_t)(c - 1) >= 127) return false;
    for (; *characters; characters++) {
        if (c == (unsigned char)*characters) return true;
    }
    return false;
}

static inline bool is_unicode_whitespace(int32_t c) {
    return c >= 0 && (c < 0x80 ? (c == ' ' || (uint32_t)(c - '\t') < 5) : iswspace((wint_t)c) != 0);
}

static inline bool at_eof(const TSLexer *lexer) {
    return lexer->lookahead == 0 && lexer->eof(lexer);
}

static bool is_syntax_word(const char *word) {
    static const char *const words[] = {
${syntaxWords.map((word) => `        "${word}",`).join('\n')}
    };
    unsigned low = 0, high = sizeof(words) / sizeof(words[0]);
    while (low < high) {
        unsigned middle = low + (high - low) / 2;
        int order = strcmp(word, words[middle]);
        if (!order) return true;
        if (order < 0) high = middle;
        else low = middle + 1;
    }
    return false;
}

${tables.map(({ declarations }) => declarations).join('\n\n')}

${helpers.join('\n\n')}

static inline bool is_ascii_id_start(int32_t character) {
    return (((uint32_t)character | 0x20u) - (uint32_t)'a' < 26u) || character == '_';
}

static inline bool is_ascii_id_continue(int32_t character) {
    return is_ascii_id_start(character) || ((uint32_t)character - (uint32_t)'0' < 10u);
}

// Lexer tables include the escape introducer; scanner readers decode escapes separately.
static inline bool is_id_start(int32_t character) {
    if (character < 0x80) return is_ascii_id_start(character);
    return ${tables[0].expression};
}

static inline bool is_id_continue(int32_t character) {
    if (character < 0x80) return is_ascii_id_continue(character);
    return ${tables[1].expression};
}

static const TSCharacterRange directive_identifier_continue_ranges[] = {
${directiveIdentifierRanges.map(([start, end]) => `    {0x${start.toString(16)}, 0x${end.toString(16)}},`).join('\n')}
};

static inline bool is_directive_identifier_continue(int32_t character) {
    if (character < 0x80) return is_ascii_id_continue(character);
    return set_contains(directive_identifier_continue_ranges, ${directiveIdentifierRanges.length}, character);
}

#endif
`
  .replaceAll('ts_lex_', 'scanner_identifier_')
  .replaceAll(/[ \t]+$/gm, '');
writeFileSync(process.argv[3], header);
