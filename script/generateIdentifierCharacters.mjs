import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

import { directiveIdentifierRanges } from './directiveIdentifierRanges.mjs';

assert.equal(process.argv.length, 4, 'Usage: generateIdentifierCharacters.mjs <parser.c> <header>');
const source = readFileSync(process.argv[2], 'utf8');
const syntaxWords = extractSyntaxWords(source);
const { startRanges, continueRanges } = extractIdentifierRanges(source);

const header =
  `/* Generated by script/generateIdentifierCharacters.mjs from ts_lex_table, ts_symbol_metadata, and Unicode properties. */
#ifndef TREE_SITTER_C_SHARP_IDENTIFIER_CHARACTERS_H_
#define TREE_SITTER_C_SHARP_IDENTIFIER_CHARACTERS_H_

#include "tree_sitter/parser.h"
#include <string.h>
#include <wctype.h>

static inline bool buf_equals(const char *buf, size_t n, const char *kw) {
    for (size_t i = 0; i < n; i++) {
        if (!kw[i] || buf[i] != kw[i]) return false;
    }
    return !kw[n];
}

// web-tree-sitter.wasm omits strchr; non-literal sets cannot lower to memchr.
static inline bool is_ascii_in(int32_t c, const char *characters) {
    if ((uint32_t)(c - 1) >= 127) return false;
    for (; *characters; characters++) {
        if (c == (unsigned char)*characters) return true;
    }
    return false;
}

static inline bool is_unicode_whitespace(int32_t c) {
    return c >= 0 && (c < 0x80 ? (c == ' ' || (uint32_t)(c - '\t') < 5) : iswspace((wint_t)c) != 0);
}

static inline bool at_eof(const TSLexer *lexer) {
    return lexer->lookahead == 0 && lexer->eof(lexer);
}

static bool is_syntax_word(const char *word) {
    static const char *const words[] = {
${syntaxWords.map((word) => `        "${word}",`).join('\n')}
    };
    unsigned low = 0, high = sizeof(words) / sizeof(words[0]);
    while (low < high) {
        unsigned middle = low + (high - low) / 2;
        int order = strcmp(word, words[middle]);
        if (!order) return true;
        if (order < 0) high = middle;
        else low = middle + 1;
    }
    return false;
}

static const TSCharacterRange identifier_start_ranges[] = {
${formatRanges(startRanges)}
};

static const TSCharacterRange identifier_continue_ranges[] = {
${formatRanges(continueRanges)}
};

static inline bool is_ascii_id_start(int32_t character) {
    return (((uint32_t)character | 0x20u) - (uint32_t)'a' < 26u) || character == '_';
}

static inline bool is_ascii_id_continue(int32_t character) {
    return is_ascii_id_start(character) || ((uint32_t)character - (uint32_t)'0' < 10u);
}

static inline bool is_id_start(int32_t character) {
    if (character < 0x80) return is_ascii_id_start(character);
    return set_contains(identifier_start_ranges, ${startRanges.length}, character);
}

static inline bool is_id_continue(int32_t character) {
    if (character < 0x80) return is_ascii_id_continue(character);
    return set_contains(identifier_continue_ranges, ${continueRanges.length}, character);
}

static const TSCharacterRange directive_identifier_continue_ranges[] = {
${formatRanges(directiveIdentifierRanges)}
};

static inline bool is_directive_identifier_continue(int32_t character) {
    if (character < 0x80) return is_ascii_id_continue(character);
    return set_contains(directive_identifier_continue_ranges, ${directiveIdentifierRanges.length}, character);
}

#endif
`.replaceAll(/[ \t]+$/gm, '');
writeFileSync(process.argv[3], header);

function extractSyntaxWords(parserSource) {
  const stringDataMatch = parserSource.match(/static const uint8_t ts_string_data\[\]\s*=\s*\{([\s\S]*?)\};/);
  const nameOffsetsMatch = parserSource.match(/static const uint32_t ts_symbol_name_offsets\[\]\s*=\s*\{([\s\S]*?)\};/);
  const metadataMatch = parserSource.match(/static const uint8_t ts_symbol_metadata\[\]\s*=\s*\{([\s\S]*?)\};/);
  assert.ok(
    stringDataMatch?.[1] && nameOffsetsMatch?.[1] && metadataMatch?.[1],
    'Missing symbol metadata tables in parser.c'
  );
  const stringData = Uint8Array.from(stringDataMatch[1].match(/\d+/g) ?? [], Number);
  const unnamedSymbols = new Set(
    [...metadataMatch[1].matchAll(/\[(\w+)\]\s*=\s*(\d+),/g)]
      .filter((match) => (Number(match[2]) & 2) === 0)
      .map((match) => match[1])
  );
  const words = new Set();
  for (const match of nameOffsetsMatch[1].matchAll(/\[(\w+)\]\s*=\s*(\d+),/g)) {
    if (!unnamedSymbols.has(match[1])) continue;
    const offset = Number(match[2]);
    const end = stringData.indexOf(0, offset);
    assert.ok(end >= offset, `Unterminated symbol string at offset ${offset}`);
    const name = Buffer.from(stringData.subarray(offset, end)).toString('utf8');
    if (/^[A-Za-z_]+$/.test(name) && name !== 'var') words.add(name);
  }
  const sorted = [...words].toSorted((left, right) => (left < right ? -1 : left > right ? 1 : 0));
  assert.ok(sorted.length > 0, 'Missing generated syntax words');
  return sorted;
}

function extractIdentifierRanges(parserSource) {
  const symbolMatch = parserSource.match(/^\s*sym__identifier_token\s*=\s*(\d+),/m);
  const tableMatch = parserSource.match(/static const uint16_t ts_lex_table\[\]\s*=\s*\{([\s\S]*?)\};/);
  assert.ok(symbolMatch?.[1] && tableMatch?.[1], 'Missing sym__identifier_token or ts_lex_table in parser.c');
  const identifierSymbol = Number(symbolMatch[1]);
  const words = Uint16Array.from(tableMatch[1].match(/\d+/g) ?? [], Number);
  const lex = createLexTableReader(words);
  const continuationState = lex.nextState(0, lex.asciiClass(0x71));
  assert.ok(continuationState >= 0 && lex.accepts(continuationState, identifierSymbol), 'Missing identifier state');
  const startClasses = classifyIdentifierClasses(lex, 0, identifierSymbol);
  const continueClasses = classifyIdentifierClasses(lex, continuationState, identifierSymbol);
  verifyAsciiIdentifierClasses(lex, startClasses, continueClasses);
  return {
    startRanges: collectUnicodeRanges(lex, startClasses),
    continueRanges: collectUnicodeRanges(lex, continueClasses),
  };
}

function classifyIdentifierClasses(lex, fromState, symbol) {
  const matched = new Uint8Array(lex.classCount);
  for (let cls = 0; cls < lex.classCount; cls++) {
    const next = lex.nextState(fromState, cls);
    if (next >= 0 && lex.accepts(next, symbol)) matched[cls] = 1;
  }
  return matched;
}

function verifyAsciiIdentifierClasses(lex, startClasses, continueClasses) {
  for (let character = 0; character < 128; character++) {
    const isStart =
      (character >= 0x41 && character <= 0x5a) || (character >= 0x61 && character <= 0x7a) || character === 0x5f;
    const isContinue = isStart || (character >= 0x30 && character <= 0x39);
    const cls = lex.asciiClass(character);
    assert.equal(
      Boolean(startClasses[cls]),
      isStart,
      `Unexpected ASCII identifier-start membership for U+${character.toString(16)}`
    );
    assert.equal(
      Boolean(continueClasses[cls]),
      isContinue,
      `Unexpected ASCII identifier-continuation membership for U+${character.toString(16)}`
    );
  }
}

function collectUnicodeRanges(lex, matchedClasses) {
  const ranges = [];
  let rangeStart = -1;
  let cursor = 128;
  for (let i = 0; i < lex.unicodeRanges; i++) {
    const endExclusive = lex.unicodeEnd(i) + 1;
    if (matchedClasses[lex.unicodeClass(i)]) {
      if (rangeStart < 0) rangeStart = cursor;
    } else if (rangeStart >= 0) {
      ranges.push([rangeStart, cursor - 1]);
      rangeStart = -1;
    }
    cursor = endExclusive;
  }
  if (rangeStart >= 0) ranges.push([rangeStart, cursor - 1]);
  assert.ok(ranges.length > 0, 'Missing non-ASCII identifier ranges');
  return ranges;
}

function formatRanges(ranges) {
  let lines = '';
  for (let i = 0; i < ranges.length; i++) {
    const [start, end] = ranges[i];
    const column = i % 8;
    const entry = `{0x${start.toString(16)}, 0x${end.toString(16)}},`;
    lines += `${column ? ' ' : '    '}${entry}${column === 7 || i === ranges.length - 1 ? '\n' : ''}`;
  }
  return lines.trimEnd();
}

function createLexTableReader(t) {
  const word = (i) => t[i] ?? 0;
  const readU32 = (i) => (word(i) | (word(i + 1) << 16)) >>> 0;
  const stateCount = word(2);
  const classCount = word(4);
  const unicodeRanges = word(5);
  const wideBase = (word(6) & 0x40_00) !== 0;
  const combLen = readU32(7);
  const extTransLen = readU32(9);
  const unicodeEndsOff = 141;
  const unicodeClassesOff = unicodeEndsOff + unicodeRanges * 2;
  const stateMetaOff = unicodeClassesOff + unicodeRanges;
  const combOff = stateMetaOff + stateCount * (wideBase ? 5 : 4);
  const extTransOff = combOff + combLen * 2;
  const extAcceptsOff = extTransOff + extTransLen;
  const layout = { word, readU32, wideBase, combLen, stateMetaOff, combOff, extTransOff, extAcceptsOff };
  return {
    classCount,
    unicodeRanges,
    asciiClass: (cp) => word(13 + cp),
    unicodeEnd: (i) => readU32(unicodeEndsOff + i * 2),
    unicodeClass: (i) => word(unicodeClassesOff + i),
    nextState: (state, cls) => readNextState(layout, state, cls),
    accepts: (state, symbol) => readAccepts(layout, state, symbol),
  };
}

function readNextState(layout, state, cls) {
  const sm = readStateMeta(layout, state);
  if (sm.tmpl === 0) return -1;
  const idx = sm.base + cls;
  const inComb = idx < layout.combLen && layout.word(layout.combOff + idx * 2) === sm.tmpl;
  const act = inComb ? layout.word(layout.combOff + idx * 2 + 1) : sm.def;
  if (act === 0) return -1;
  if ((act & 0x80_00) === 0) return act & 0x40_00 ? -1 : (act & 0x1f_ff) - 1;
  const p = layout.extTransOff + (act & 0x7f_ff);
  return layout.word(p + 1) & 0x80_00 ? -1 : layout.word(p);
}

function readAccepts(layout, state, symbol) {
  const acc = readStateMeta(layout, state).acc;
  if (acc === 0) return false;
  if ((acc & 0x80_00) === 0) return (acc & 0x3f_ff) - 1 === symbol;
  let p = layout.extAcceptsOff + (acc & 0x7f_ff);
  const flags = layout.word(p++);
  const fallbackSym = flags & 1 ? layout.word(p) : -1;
  if (flags & 1) p += 4;
  if (flags & 2) return fallbackSym === symbol;
  return Boolean(flags & 4) && layout.word(p) === symbol;
}

function readStateMeta(layout, state) {
  const o = layout.stateMetaOff + state * (layout.wideBase ? 5 : 4);
  return layout.wideBase
    ? { base: layout.readU32(o), tmpl: layout.word(o + 2), def: layout.word(o + 3), acc: layout.word(o + 4) }
    : { base: layout.word(o), tmpl: layout.word(o + 1), def: layout.word(o + 2), acc: layout.word(o + 3) };
}
